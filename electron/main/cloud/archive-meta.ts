/**
 * Метаданные облачного архива сборки.
 *
 * Вынесено в отдельный модуль, потому что `upload-worker.ts` — это точка входа
 * worker-потока с самозапуском (`void run()`): импортировать константы прямо оттуда
 * нельзя, иначе при загрузке модуля в main-процессе отработает запуск воркера.
 */

/**
 * Путь метазаписи с иконкой сборки внутри архива. Иконка хранится в БД (data-URL),
 * а не в папке интента, поэтому она кладётся в zip отдельным файлом. Каталог
 * `.xnlauncher/` не пересекается с категориями содержимого и не мешает обходу файлов.
 */
export const META_ICON_ENTRY = ".xnlauncher/icon.txt"

/**
 * Путь метазаписи с настоящим именем сборки внутри архива.
 *
 * Имя файла архива в облаке и на диске проходит санитайзер (в имени файла Windows
 * нельзя `:`, `?`, `*`), поэтому сборка `Prominence™ II: Hasturian Era` лежит как
 * `Prominence™ II_ Hasturian Era.zip`. Без этой записи восстановленная из облака
 * сборка получала бы имя по имени файла, то есть с `_` вместо `:`.
 */
export const META_NAME_ENTRY = ".xnlauncher/name.txt"
