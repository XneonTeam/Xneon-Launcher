/**
 * Build-time определение GitHub-репозитория.
 *
 * Приоритет источников:
 *  1. `GITHUB_REPOSITORY` — GitHub Actions всегда передаёт `owner/repo`.
 *  2. `XNLC_REPOSITORY` — явное переопределение для локальной/упакованной сборки.
 *  3. Git remote текущего проекта: `origin`, затем `upstream`, затем остальные.
 *
 * Runtime сюда не обращается: для него идентичность встраивается генератором.
 */
import { execFileSync } from "node:child_process"
import {
  normalizeRepositoryIdentity,
  parseRepositoryIdentity,
  repositoryFromGitRemoteUrl,
} from "../lib/repository-identity"

export const REPOSITORY_ENV_KEYS = ["GITHUB_REPOSITORY", "XNLC_REPOSITORY"] as const

export type RepositoryEnvironment = Record<string, string | undefined>

/** Первое валидное значение `GITHUB_REPOSITORY`/`XNLC_REPOSITORY`. */
export function repositoryFromEnvironment(env: RepositoryEnvironment = process.env): string | null {
  for (const key of REPOSITORY_ENV_KEYS) {
    const repository = parseRepositoryIdentity(env[key])
    if (repository) return repository
  }
  return null
}

function git(cwd: string, args: string[]): string {
  try {
    return execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim()
  } catch {
    return ""
  }
}

/** Имена настроенных remotes (пустой список, если Git недоступен). */
export function gitRemoteNames(cwd = process.cwd()): string[] {
  return git(cwd, ["remote"]).split(/\r?\n/).map(name => name.trim()).filter(Boolean)
}

/**
 * Ищет GitHub-remote в детерминированном порядке. `origin` важнее `upstream`:
 * сборка из форка должна использовать идентичность форка, а не апстрима.
 */
export function repositoryFromGit(cwd = process.cwd()): string | null {
  const remotes = gitRemoteNames(cwd)
  const ordered = ["origin", "upstream", ...remotes.filter(name => name !== "origin" && name !== "upstream")]
  for (const remote of ordered) {
    const repository = repositoryFromGitRemoteUrl(git(cwd, ["config", "--get", `remote.${remote}.url`]))
    if (repository) return repository
  }
  return null
}

export type ResolveRepositoryOptions = {
  env?: RepositoryEnvironment
  cwd?: string
  fromGit?: (cwd: string) => string | null
}

/** Единая точка определения `owner/repo` для build-скриптов. */
export function resolveRepositoryIdentity(options: ResolveRepositoryOptions = {}): string {
  const fromEnvironment = repositoryFromEnvironment(options.env)
  if (fromEnvironment) return fromEnvironment
  const fromGit = (options.fromGit ?? repositoryFromGit)(options.cwd ?? process.cwd())
  if (fromGit) return fromGit
  throw new Error(
    "Cannot determine the GitHub repository for this build: set GITHUB_REPOSITORY or XNLC_REPOSITORY, " +
    "or add a github.com git remote",
  )
}

/** Содержимое build-time модуля идентичности (попадает в собранный бандл). */
export function renderRepositoryIdentityModule(repository: unknown): string {
  const identity = normalizeRepositoryIdentity(repository)
  return [
    "/* auto-generated by scripts/gen-repository-identity.ts -- DO NOT EDIT */",
    "/** GitHub repository this build was produced from. */",
    `export const repositoryIdentity = ${JSON.stringify(identity)}`,
    "",
  ].join("\n")
}
