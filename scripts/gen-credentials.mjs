import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const outDir = path.join(root, "electrobun", "main", "cloud")
const outFile = path.join(outDir, "credentials.generated.ts")

function loadDotEnv() {
  const envFile = path.join(root, ".env")
  if (!fs.existsSync(envFile)) return
  for (const line of fs.readFileSync(envFile, "utf-8").split(/\r?\n/)) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith("#")) continue
    const eq = trimmed.indexOf("=")
    if (eq === -1) continue
    const key = trimmed.slice(0, eq).trim()
    let value = trimmed.slice(eq + 1).trim()
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1)
    }
    if (process.env[key] === undefined) process.env[key] = value
  }
}

if (process.env.XNLC_SKIP_LOCAL_DOTENV !== "1") loadDotEnv()

const read = (name) => process.env[name] || ""

const creds = {
  googleDrive: { clientId: read("GOOGLE_DRIVE_CLIENT_ID"), clientSecret: read("GOOGLE_DRIVE_CLIENT_SECRET") },
  dropbox: { clientId: read("DROPBOX_CLIENT_ID") },
  yandex: { clientId: read("YANDEX_CLIENT_ID") },
  onedrive: { clientId: read("ONEDRIVE_CLIENT_ID") },
  elyby: { clientId: read("ELY_CLIENT_ID"), clientSecret: read("ELY_CLIENT_SECRET"), deviceClientId: read("ELY_DEVICE_CLIENT_ID") },
  xnskins: { clientId: read("XN_CLIENT_ID"), clientSecret: read("XN_CLIENT_SECRET") },
  microsoft: { clientId: read("MICROSOFT_CLIENT_ID") },
  microsoftDevice: { clientId: read("MICROSOFT_DEVICE_CLIENT_ID") },
}

// Релизная сборка не должна молча уехать пользователям со сломанным входом.
// Имена пустых переменных печатаем, значения — никогда.
const REQUIRED_CREDENTIALS = [
  "GOOGLE_DRIVE_CLIENT_ID",
  "GOOGLE_DRIVE_CLIENT_SECRET",
  "DROPBOX_CLIENT_ID",
  "YANDEX_CLIENT_ID",
  "ONEDRIVE_CLIENT_ID",
  "ELY_CLIENT_ID",
  "ELY_CLIENT_SECRET",
  "ELY_DEVICE_CLIENT_ID",
  "MICROSOFT_CLIENT_ID",
  "MICROSOFT_DEVICE_CLIENT_ID",
]

// XN Skins берёт client_id из electrobun/main/auth.ts, поэтому generated-значения
// остаются ради совместимости, но обязательными для сборки не являются.
const LEGACY_CREDENTIALS = ["XN_CLIENT_ID", "XN_CLIENT_SECRET"]

if (process.env.XNLC_REQUIRE_CLOUD_CREDENTIALS === "1") {
  const missing = REQUIRED_CREDENTIALS.filter((name) => !read(name).trim())
  if (missing.length > 0) {
    console.error(`[gen-credentials] missing required cloud credentials: ${missing.join(", ")}`)
    console.error("[gen-credentials] add them as repository secrets for the release workflows")
    process.exit(1)
  }
  const legacyMissing = LEGACY_CREDENTIALS.filter((name) => !read(name).trim())
  if (legacyMissing.length > 0) {
    console.warn(`[gen-credentials] legacy credentials are empty: ${legacyMissing.join(", ")}`)
  }
}

const content = `/* auto-generated by scripts/gen-credentials.mjs -- DO NOT EDIT */
export const cloudCredentials = ${JSON.stringify(creds, null, 2)}
`

fs.mkdirSync(outDir, { recursive: true })
fs.writeFileSync(outFile, content)
console.log(`[gen-credentials] wrote ${path.relative(root, outFile)}`)
